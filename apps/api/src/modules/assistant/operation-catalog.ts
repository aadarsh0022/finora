export interface OperationSpec {
  title: string;
  schema: z.ZodType;
  method: 'POST' | 'PATCH' | 'DELETE';
  collection?: string;
  parentCollection?: string;
  parentField?: string;
  path: (id: string, parent: string) => string;
  preset?: Record<string, unknown>;
  impact: string;
}
